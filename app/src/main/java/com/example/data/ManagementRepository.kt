    fun getModelsForCategory(categoryId: String): List<ManagementModel> {
        return models.filter { it.categoryIds.contains(categoryId) }
    }

    fun getModelById(modelId: String): ManagementModel? {
        return models.find { it.id == modelId }
    }

    fun searchModels(query: String): List<ManagementModel> {
        if (query.isBlank()) return emptyList()
        val q = query.lowercase().trim()
        return models.filter { model ->
            model.title.lowercase().contains(q) ||
                    (model.abbreviation?.lowercase()?.contains(q) == true) ||
                    model.definition.lowercase().contains(q) ||
                    model.categoryName.lowercase().contains(q) ||
                    model.purpose.lowercase().contains(q) ||
                    model.workplaceExample.lowercase().contains(q)
        }
    }
